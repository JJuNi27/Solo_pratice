# ==============================
# Python math 모듈 정리
# ==============================

import math

# --------------------------------------------------
# 0. 기본
# --------------------------------------------------
# math 모듈:
# 수학 관련 함수들을 모아둔 파이썬 기본 모듈
#
# 사용법:
# import math
# math.함수이름(...)
#
# 예)
# print(math.sqrt(16))   # 4.0


# --------------------------------------------------
# 1. 수학 상수
# --------------------------------------------------
print("=== 수학 상수 ===")
print(math.pi)    # 원주율 π = 3.141592...
print(math.e)     # 자연상수 e = 2.718281...
print(math.tau)   # 2π
print(math.inf)   # 무한대
print(-math.inf)  # 음의 무한대
print(math.nan)   # NaN (숫자가 아님)
print()


# --------------------------------------------------
# 2. 올림 / 내림 / 버림 / 절댓값
# --------------------------------------------------
print("=== 올림 / 내림 / 버림 / 절댓값 ===")
print(math.ceil(3.2))    # 4   : 올림
print(math.floor(3.8))   # 3   : 내림
print(math.trunc(3.8))   # 3   : 소수점 버림
print(math.trunc(-3.8))  # -3  : 0쪽으로 버림
print(math.fabs(-7.2))   # 7.2 : 절댓값(float 반환)
print(abs(-7.2))         # 7.2 : 내장 함수 abs
print()

# 참고:
# abs()는 내장 함수라서 math 없이 바로 사용 가능
# 백준에서는 보통 abs()를 더 자주 씀


# --------------------------------------------------
# 3. 제곱, 제곱근, 정수 제곱근
# --------------------------------------------------
print("=== 제곱 / 제곱근 ===")
print(math.sqrt(25))     # 5.0   : 제곱근
print(5 ** 2)            # 25    : 제곱
print(math.pow(2, 3))    # 8.0   : 거듭제곱 (float 반환)
print(2 ** 3)            # 8     : 거듭제곱 연산자
print(math.isqrt(25))    # 5     : 정수 제곱근
print(math.isqrt(27))    # 5     : floor(sqrt(27))
print()

# 실전 팁:
# 1) 정수 거듭제곱은 보통 ** 가 더 자주 쓰임
# 2) N 이하 완전제곱수 개수 같은 문제는 math.isqrt(N) 자주 씀


# --------------------------------------------------
# 4. 최대공약수 / 최소공배수
# --------------------------------------------------
print("=== gcd / lcm ===")
print(math.gcd(12, 18))      # 6   : 최대공약수
print(math.lcm(12, 18))      # 36  : 최소공배수
print(math.gcd(24, 36, 48))  # 12  : 여러 개도 가능
print(math.lcm(4, 6, 8))     # 24
print()

# 실전 팁:
# gcd = greatest common divisor = 최대공약수
# lcm = least common multiple = 최소공배수


# --------------------------------------------------
# 5. 팩토리얼 / 조합 / 순열
# --------------------------------------------------
print("=== 팩토리얼 / 조합 / 순열 ===")
print(math.factorial(5))   # 120  : 5! = 5*4*3*2*1
print(math.comb(5, 2))     # 10   : 5C2
print(math.perm(5, 2))     # 20   : 5P2
print()

# 공식
# 조합: nCk = 순서 없이 k개 선택
# 순열: nPk = 순서 있게 k개 선택

# 예)
# math.comb(5, 2) = 10
# -> 5개 중 2개 고르는 경우의 수


# --------------------------------------------------
# 6. 로그 / 지수
# --------------------------------------------------
print("=== 로그 / 지수 ===")
print(math.exp(1))       # e^1
print(math.log(math.e))  # 자연로그 ln(e) = 1.0
print(math.log(8, 2))    # 밑이 2인 로그 -> 3.0
print(math.log2(8))      # 3.0
print(math.log10(100))   # 2.0
print()

# 실전 팁:
# 알고리즘에서는 log2()가 가끔 나옴
# 예: 이진 탐색, 트리 높이 감 잡을 때


# --------------------------------------------------
# 7. 나머지 관련
# --------------------------------------------------
print("=== 나머지 관련 ===")
print(10 % 3)                # 1   : 일반 나머지
print(math.fmod(10, 3))      # 1.0 : 실수 기반 나머지
print(math.remainder(10, 3)) # 가장 가까운 정수배 기준 나머지
print()

# 실전 팁:
# 백준에서는 대부분 % 만 쓰면 됨
# fmod(), remainder()는 특수한 실수 계산에서 사용


# --------------------------------------------------
# 8. 삼각함수
# --------------------------------------------------
print("=== 삼각함수 ===")
print(math.sin(math.pi / 2))   # 1.0
print(math.cos(0))             # 1.0
print(math.tan(math.pi / 4))   # 1.0
print()

# 주의:
# sin, cos, tan은 "도(degree)"가 아니라 "라디안(radian)" 기준


# --------------------------------------------------
# 9. 각도 변환
# --------------------------------------------------
print("=== 각도 변환 ===")
print(math.radians(180))   # 180도 -> π 라디안
print(math.degrees(math.pi))  # π 라디안 -> 180도
print()

# 공식
# degree -> radian: math.radians(각도)
# radian -> degree: math.degrees(라디안)


# --------------------------------------------------
# 10. 역삼각함수
# --------------------------------------------------
print("=== 역삼각함수 ===")
print(math.asin(1))        # π/2
print(math.acos(1))        # 0
print(math.atan(1))        # π/4
print(math.atan2(1, 1))    # y=1, x=1 일 때 각도
print()

# atan2(y, x)는 좌표 문제에서 방향/각도 계산할 때 자주 씀


# --------------------------------------------------
# 11. 거리 계산
# --------------------------------------------------
print("=== 거리 계산 ===")
print(math.hypot(3, 4))              # 5.0 : sqrt(3^2 + 4^2)
print(math.dist((1, 2), (4, 6)))     # 두 점 사이 거리
print()

# 실전 팁:
# hypot(a, b)는 직각삼각형 빗변 길이 계산 느낌
# dist(p, q)는 좌표 2개 거리


# --------------------------------------------------
# 12. 합 계산 정확도
# --------------------------------------------------
print("=== 정확한 합 ===")
print(sum([0.1, 0.2, 0.3]))          # 부동소수점 오차 가능
print(math.fsum([0.1, 0.2, 0.3]))    # 더 정확한 합
print()

# 실전 팁:
# 백준에서는 대부분 sum으로 충분
# 소수 오차가 민감하면 fsum 고려


# --------------------------------------------------
# 13. 곱 계산
# --------------------------------------------------
print("=== 곱 계산 ===")
print(math.prod([1, 2, 3, 4]))   # 24
print()

# 실전 팁:
# 리스트 원소 전부 곱할 때 편함
# 예: [2, 3, 5] -> 30


# --------------------------------------------------
# 14. 실수 분리
# --------------------------------------------------
print("=== 정수부 / 소수부 분리 ===")
fractional, integer = math.modf(3.75)
print(fractional)   # 0.75
print(integer)      # 3.0
print()

# modf(x) -> (소수부, 정수부)


# --------------------------------------------------
# 15. 실수 검사
# --------------------------------------------------
print("=== 숫자 상태 검사 ===")
print(math.isfinite(10))         # True  : 유한한 수인가?
print(math.isinf(math.inf))      # True  : 무한대인가?
print(math.isnan(math.nan))      # True  : NaN인가?
print()

# 실전 팁:
# 특수한 수 처리할 때 사용
# 백준에서는 자주 쓰진 않음


# --------------------------------------------------
# 16. 실수 비교
# --------------------------------------------------
print("=== 실수 비교 ===")
print(0.1 + 0.2 == 0.3)                      # False 일 수 있음
print(math.isclose(0.1 + 0.2, 0.3))          # True
print(math.isclose(100.0, 100.1, rel_tol=1e-3))  # 상대오차 허용 비교
print()

# 실전 팁:
# 실수는 정확히 같다고 비교하면 오차 때문에 문제 생길 수 있음
# 그럴 때 isclose() 사용


# --------------------------------------------------
# 17. frexp / ldexp (고급)
# --------------------------------------------------
print("=== frexp / ldexp ===")
mantissa, exponent = math.frexp(8)
print(mantissa, exponent)      # 8 = mantissa * (2 ** exponent)

print(math.ldexp(0.5, 4))      # 0.5 * (2 ** 4) = 8.0
print()

# 이건 보통 초보 단계에서는 거의 안 씀
# 그냥 "이런 것도 있다" 정도로만 보면 됨


# --------------------------------------------------
# 18. round는 math가 아니라 내장 함수
# --------------------------------------------------
print("=== round ===")
print(round(3.14159, 2))   # 3.14
print(round(1234, -2))     # 1200
print(round(2.5))          # 2
print(round(3.5))          # 4
print()

# 주의:
# round()는 "무조건 0.5 올림"처럼 생각하면 안 됨
# 파이썬은 가까운 짝수 쪽으로 반올림하는 경우가 있음


# --------------------------------------------------
# 19. 백준에서 진짜 자주 쓰는 것만 추리면
# --------------------------------------------------
# math.isqrt(N)      : 정수 제곱근
# math.gcd(a, b)     : 최대공약수
