# 그대로 출력하기

# 입력 받은 대로 출력하는 프로그램을 작성하시오.

# 입력이 주어진다. 입력은 최대 100줄로 이루어져 있고, 알파벳 소문자, 대문자, 공백, 숫자로만 이루어져 있다. 각 줄은 100글자를 넘지 않으며, 빈 줄은 주어지지 않는다. 또, 각 줄은 공백으로 시작하지 않고, 공백으로 끝나지 않는다.

import sys

for line in sys.stdin:
    print(line, end='')
    
# end=''를 해줘야 줄바꿈이 두 번 되지 않음
# print(line)만 하면 이미 line에 줄바꿈이 포함되어 있어서
# 출력할 때 또 줄바꿈이 되기 때문
# sys.stdin을 사용하면 입력이 더 이상 없을 때까지 계속 입력을 받음
# 따라서 여러 줄의 입력을 처리할 때 유용함
# 단, 온라인 저지에서는 입력이 끝나는 시점을 알 수 없기 때문에
