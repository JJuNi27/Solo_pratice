# 단어 공부

# 알파벳 대소문자로 된 단어가 주어지면, 이 단어에서 가장 많이 사용된 알파벳이 무엇인지 알아내는 프로그램을 작성하시오. 단, 대문자와 소문자를 구분하지 않는다.

# 첫째 줄에 알파벳 대소문자로 이루어진 단어가 주어진다. 주어지는 단어의 길이는 1,000,000을 넘지 않는다.

N = input().upper()
cnt = [0] * 26

for ch in N:
    cnt[ord(ch) - ord('A')] += 1

mx = max(cnt)

if cnt.count(mx) > 1:
    print("?")
else:
    print(chr(cnt.index(mx) + ord('A')))

# 해석
# 1. 입력받은 단어를 모두 대문자로 변환하여 N에 저장합니다.
# 2. 알파벳 개수(26개)만큼의 리스트 cnt를 생성하고, 각 알파벳의 출현 빈도를 저장합니다.
# 3. N의 각 문자에 대해, 해당 문자의 아스키 코드 값을 이용하여 cnt 리스트에서 해당 알파벳의 인덱스를 계산하고, 그 인덱스의 값을 1 증가시킵니다.
# 4. cnt 리스트에서 가장 큰 값을 mx에 저장합니다.
# 5. cnt 리스트에서 mx의 개수를 세어, 만약 2개 이상이면 "?"를 출력하고, 그렇지 않으면 mx의 인덱스를 이용하여 해당 알파벳을 출력합니다.
# 6. chr 함수를 사용하여 인덱스를 다시 문자로 변환할 때, 'A'의 아스키 코드 값을 더해줍니다.
# 이 코드는 대소문자를 구분하지 않고 가장 많이 사용된 알파벳을 찾아 출력하는 프로그램입니다.