# 창문 닫기

# 예를 들어 현재 3개의 창문이 있고 3명의 사람이 있을 때,

# 1번째 사람은 1의 배수인 1,2,3번 창문을 연다. (1, 1, 1)
# 2번째 사람은 2의 배수인 2번 창문을 닫는다. (1, 0, 1)
# 3번째 사람은 3의 배수인 3번 창문을 닫는다. (1, 0, 0)
# 결과적으로 마지막에 열려 있는 창문의 개수는 1개 이다.

# 첫 번째 줄에는 창문의 개수와 사람의 수 N(1 ≤ N ≤ 2,100,000,000)이 주어진다.

# 마지막에 열려 있는 창문의 개수를 출력한다.

import math

N = int(input())
print(math.isqrt(N))

# 창문 번호 k는 k의 약수 번호 사람들에 의해 토글됨
# 따라서 k번 창문이 토글되는 횟수 = k의 약수 개수
# 마지막에 열려 있으려면 토글 횟수가 홀수여야 함
# 약수는 보통 짝을 이루므로 개수는 짝수
# 하지만 완전제곱수는 가운데 약수가 겹쳐서 약수 개수가 홀수
# 따라서 마지막에 열려 있는 창문은 완전제곱수 번호뿐
# 답 = N 이하의 완전제곱수 개수 = int(sqrt(N)) = math.isqrt(N)