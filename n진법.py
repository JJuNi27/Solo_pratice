# ✔ 진법이란?

# 숫자를 표현할 때 한 자리에 올 수 있는 최대 값 기준

# | 진법   | 사용 숫자 | 예시 |
# | ----- | --------- | ------ |
# | 2진법  | 0,1      | `1011` |
# | 8진법  | 0~7      | `17`   |
# | 10진법 | 0~9      | `123`  |
# | 16진법 | 0~9, A~F | `1A`   |

# 2️⃣ 파이썬에서 n진법 → 10진법 (제일 중요)
# 🔑 핵심 문법

int("1011", 2)   # 2진수 → 10진수
# 결과: 11

int("17", 8)     # 8진수 → 10진수
# 결과: 15

int("1A", 16)    # 16진수 → 10진수
# 결과: 26

# int(1011, 2)   # ❌ 에러
# int("1011", 2) # ⭕

# 3️⃣ 10진법 → n진법 (출력 문제 자주 나옴)
# 기본 함수 3종 세트
# bin(10)  # '0b1010' # 2진법
# oct(10)  # '0o12' # 8진법
# hex(10)  # '0xa' # 16진법

# ❗ 앞에 붙은 접두어 제거
# bin(10)[2:]  # '1010'
# oct(10)[2:]  # '12'
# hex(10)[2:]  # 'a'


