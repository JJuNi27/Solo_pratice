# ✅ 딕셔너리(dict)

# “이름표(key) → 값(value)” 형태로 저장하는 구조

# 인덱스가 아니라 **키(key)**로 접근해

# d = {"apple": 3, "banana": 1}
# print(d["apple"])  # 3

