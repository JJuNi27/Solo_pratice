# 1️⃣ round() 기본 개념 (먼저 이거부터)
# round(숫자)


# 👉 소수점 첫째 자리에서 반올림해서 정수로 만들어 줌

round(3.2)   # 3
round(3.7)   # 4
round(3.5)   # ❗ 4 아님 (아래에서 설명)

# 2️⃣ 소수점 몇 자리까지 반올림할지 정할 수도 있음
# round(숫자, 자릿수)

round(3.14159, 2)   # 3.14
round(3.14159, 3)   # 3.142
round(123.456, 1)   # 123.5

# 3️⃣ ⚠️ 파이썬 round()의 핵심 함정 (진짜 중요)

# 파이썬의 round()는
# 👉 **“사사오입 반올림”이 아니라 “은행가 반올림”**을 사용함

# 🔹 은행가 반올림이란?

# 딱 0.5일 때

# 가장 가까운 “짝수”로 감

round(2.5)   # 2
round(3.5)   # 4
round(4.5)   # 4
round(5.5)   # 6


