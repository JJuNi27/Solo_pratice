# ❗ 백준 / 시험에서 은근히 사람 많이 당함

# 5️⃣ 코딩 실전 야메꿀팁 ⭐
# ✔ 문제에서 “일반적인 반올림”이 필요하면?

# (즉, 2.5 → 3, 3.5 → 4 처럼)

import math
math.floor(x + 0.5)

math.floor(2.5 + 0.5)  # 3
math.floor(3.5 + 0.5)  # 4