# 정수 a, b, c, d, e, f가 공백으로 구분되어 차례대로 주어진다. (-999 <= a,b,c,d,e,f <= 999)
# 문제에서 언급한 방정식을 만족하는 (x,y)가 유일하게 존재하고, 이 때 x와 y가 각각 -999 이상 999 이하의 정수인 경우만 입력으로 주어짐이 보장된다.

# 문제의 답인 x와 y를 공백으로 구분해 출력한다.

a, b, c, d, e, f = map(int, input().split())

det = a*e - b*d

x = int((c*e - b*f) / det)
y = int((a*f - c*d) / det)

print(x, y)

